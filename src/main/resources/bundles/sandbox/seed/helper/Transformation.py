from typing import List
from .SchemaNode import SchemaNode


class Transformation:
    """
    A class that represents a transformation from n input columns to m output columns.
    To be used in the FedDB with the dataimporter.
    For now only supports transformation functions using row as the input parameter.
    Also does not support lists as cell values, only single values.
    Represents:
    1. Mapping from input schemanodes to transformation function specific input column names
    2. A transformation function that does some processing on the input data
    3. Output column names generated by the transformation function
    4. Mapping from the output column names to the output schema nodes
    """
    name: str

    def __init__(self, name: str, module: str,
                 input_schemanodes: List[SchemaNode],
                 in_column_names: List[str],
                 transformation_name: str,
                 out_column_names: List[str],
                 output_schemanodes: List[SchemaNode],):
        self.name = name
        self.module = module
        if len(input_schemanodes) != len(in_column_names):
            raise ValueError("Input schemanodes and input column names must have the same length.")
        self.__input_schemanodes = input_schemanodes
        self.__in_column_names = in_column_names
        self.transformation_name = transformation_name
        if len(out_column_names) != len(output_schemanodes):
            raise ValueError("Output column names and output schemanodes must have the same length.")
        self.__out_column_names = out_column_names
        self.__output_schemanodes = output_schemanodes

    def get_input_schemanodes(self) -> List[SchemaNode]:
        """
        Returns the input schemanodes of the transformation.
        """
        return self.__input_schemanodes

    def get_output_schemanodes(self) -> List[SchemaNode]:
        """
        Returns the output schemanodes of the transformation.
        """
        return self.__output_schemanodes

    def return_JSON_representation(self):
        """
        Returns a JSON representation of the transformation to be used in the connector POST
        request.
        """
        return {
            "module": self.module,
            "methodName": self.transformation_name,
            "parameters": [
                {
                    "name": "row",
                    "keys": self.__in_column_names,
                    "type": "string",
                    "choices": [],
                    "defaultValue": None,
                    "doc": f"One row of the input csv. Contains the columns: {', '.join(self.__in_column_names)}."
                }
            ],
            "returnKeys": self.__out_column_names,
            "inputMapping": {node.corresponding_column_name: self.__in_column_names[idx] for idx, node in enumerate(self.__input_schemanodes)},
            "returnMapping": {self.__out_column_names[idx]: node.corresponding_column_name for idx, node in enumerate(self.__output_schemanodes)},
            "column": "",
            "onRow": True,
            "forList": False,
            "doc": f"Transformation function that processes the input columns: {', '.join(self.__in_column_names)} and returns the output columns: {', '.join(self.__out_column_names)}."
        }
